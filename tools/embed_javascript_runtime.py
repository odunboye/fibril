#!/usr/bin/env python3
"""Embed the JavaScript runtime into portable compiler executables."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'runtime/javascript/fibril_runtime.mjs'
OUTPUT = ROOT / 'src/Fibril/Driver/JavaScript/RuntimeSource.idr'
def generated():
    text = SOURCE.read_text(encoding='utf-8')
    digest = hashlib.sha256(text.encode()).hexdigest()
    embedded = text.replace('export function runProgram(', 'function runProgram(', 1)
    return ('-- Generated by tools/embed_javascript_runtime.py; do not edit.\n'
            '-- Source SHA256: ' + digest + '\n'
            'module Fibril.Driver.JavaScript.RuntimeSource\n\n%default total\n\n'
            'public export\nruntimeSource : String\nruntimeSource = ' + json.dumps(embedded, ensure_ascii=False) + '\n')
def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    expected=generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != expected:
            raise SystemExit('Stale JavaScript runtime: run python3 tools/embed_javascript_runtime.py')
    else:
        OUTPUT.write_text(expected,encoding='utf-8')
if __name__=='__main__': main()
