#!/usr/bin/env python3
"""Embed the checked-in Fibril prelude for portable compiler executables."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "stdlib/Prelude.fib"
OUTPUT = ROOT / "src/Fibril/Driver/PreludeSource.idr"


def generated():
    text = SOURCE.read_text(encoding="utf-8")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return ('-- Generated by tools/embed_prelude.py; do not edit.\n'
            '-- Source SHA256: ' + digest + '\n'
            'module Fibril.Driver.PreludeSource\n\n%default total\n\n'
            'public export\npreludeSource : String\npreludeSource = ' +
            json.dumps(text, ensure_ascii=False) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Stale bundled prelude: run python3 tools/embed_prelude.py")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
